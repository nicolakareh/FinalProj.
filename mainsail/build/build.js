/* ---------------- Service pages ---------------- */
function servicePage(s, i) {
  const root = '../';
  const prev = services[(i - 1 + services.length) % services.length];
  const next = services[(i + 1) % services.length];
  const title = `${s.title} — ${site.name}`;
  const jsonld = { '@context': 'https://schema.org', '@type': 'Service', name: s.title, description: s.short, provider: { '@type': 'ProfessionalService', name: site.name, url: site.url }, url: `${site.url}/services/${s.slug}.html` };
  let h = head({ title, desc: s.short, canonical: `${site.url}/services/${s.slug}.html`, root, jsonld, ogImage: `${site.url}/assets/img/${s.img}-1800.jpg` });
  h += header(root, 'services');
  h += `<main id="main">
<section class="page-hero">
<div class="wrap">
<div class="page-hero__meta">
<a class="link" href="${root}index.html#services">${ICON.arrowBack} All services</a>
<span class="eyebrow">Service ${s.n} / 05</span>
</div>
<h1 class="display lines"><span class="line"><span>${esc(s.title)}</span></span></h1>
<p class="lede" data-reveal style="--d:.2s">${esc(s.short)}</p>
<div class="page-hero__art reveal-img">${img(s.img, s.title, { eager: true }, root)}</div>
</div>
</section>
<section class="section article" style="padding-top:clamp(40px,6vw,88px)">
<div class="wrap">
<aside class="article__aside" data-reveal>
<span class="eyebrow">Overview</span>
<p class="body">${esc(site.description)}</p>
<a class="link link--fwd" href="${root}index.html#contact">Start a conversation ${ICON.arrow}</a>
</aside>
<div class="article__body">
<p data-reveal>${esc(s.intro)}</p>
${s.body.map((p, k) => `<p data-reveal style="--d:${0.05 * (k + 1)}s">${esc(p)}</p>`).join('\n')}
${s.capabilities.length ? `<h3 class="h3" data-reveal>What this includes</h3>
<div class="capabilities">
${s.capabilities.map((c, k) => `<div class="capability" data-reveal style="--d:${0.06 * k}s"><span class="num">0${k + 1}</span><div><h3 class="h4">${esc(c.title)}</h3><p>${esc(c.text)}</p></div></div>`).join('\n')}
</div>` : ''}
</div>
</div>
</section>
<section class="svc-nav">
<div class="wrap">
<a href="${prev.slug}.html"><span class="eyebrow">Previous · ${prev.n}</span><span class="h3">${esc(prev.title)}</span></a>
<a href="${next.slug}.html"><span class="eyebrow">Next · ${next.n}</span><span class="h3">${esc(next.title)}</span></a>
</div>
</section>
</main>
`;
  h += footer(root);
  return h;
}

/* ---------------- Write ---------------- */
fs.mkdirSync(path.join(ROOT, 'services'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'index.html'), homePage());
services.forEach((s, i) => fs.writeFileSync(path.join(ROOT, 'services', `${s.slug}.html`), servicePage(s, i)));
const urls = [`${site.url}/`, ...services.map(s => `${site.url}/services/${s.slug}.html`)];
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(u => `<url><loc>${u}</loc></url>`).join('\n')}\n</urlset>\n`);
fs.writeFileSync(path.join(ROOT, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${site.url}/sitemap.xml\n`);
console.log('built: index.html, ' + services.map(s => `services/${s.slug}.html`).join(', ') + ', sitemap.xml, robots.txt');
