// Builds the static site: node mainsail/build/build.js
// Reads copy from data.js, writes index.html, services/*.html, sitemap.xml, robots.txt.
'use strict';
const fs = require('fs');
const path = require('path');
const { site, services, sectors, pillars, phases, home } = require('./data.js');

const ROOT = path.join(__dirname, '..');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const LOGO = fs.readFileSync(path.join(ROOT, 'assets', 'img', 'logo.svg'), 'utf8').replace('<svg ', '<svg class="brand__logo" ');
const ICON = {
  arrow: '<svg viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M3 8h10M9 4l4 4-4 4"/></svg>',
  arrowBack: '<svg viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M13 8H3M7 4L3 8l4 4"/></svg>',
  arrowUp: '<svg viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M4 12L12 4M6 4h6v6"/></svg>',
};

/* Responsive image: files generated by build/images.js as assets/img/<key>-{900,1800,2600}.{avif,webp,jpg} */
function img(key, alt, { sizes = '100vw', eager = false, cls = '' } = {}, root = '') {
  const b = `${root}assets/img/${key}`;
  const set = (ext) => `${b}-900.${ext} 900w, ${b}-1800.${ext} 1800w, ${b}-2600.${ext} 2600w`;
  return `<picture${cls ? ` class="${cls}"` : ''}><source type="image/avif" srcset="${set('avif')}" sizes="${sizes}"><source type="image/webp" srcset="${set('webp')}" sizes="${sizes}"><img src="${b}-1800.jpg" srcset="${set('jpg')}" sizes="${sizes}" alt="${esc(alt)}" width="1800" height="1200"${eager ? ' fetchpriority="high" decoding="async"' : ' loading="lazy" decoding="async"'}></picture>`;
}

