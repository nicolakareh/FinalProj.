/* Responsive image helper. Expects files generated by build/images.js:
   assets/img/<key>-{900,1800}.{avif,webp,jpg} */
function img(key, alt, { sizes = '100vw', eager = false, cls = '' } = {}, root = '') {
  const b = `${root}assets/img/${key}`;
  const set = (ext) => `${b}-900.${ext} 900w, ${b}-1800.${ext} 1800w`;
  return `<picture>
<source type="image/avif" srcset="${set('avif')}" sizes="${sizes}">
<source type="image/webp" srcset="${set('webp')}" sizes="${sizes}">
<img src="${b}-1800.jpg" srcset="${set('jpg')}" sizes="${sizes}" alt="${esc(alt)}" width="1800" height="1200"${eager ? ' fetchpriority="high" decoding="async"' : ' loading="lazy" decoding="async"'}${cls ? ` class="${cls}"` : ''}>
</picture>`;
}

